"""Build a single-file Kaggle script kernel that carries pilot/ and third_party/sauer/ inside it.

Kaggle uploads one code file per kernel, so the code is packed as a base64 tar.gz and unpacked on
the worker. Usage (from the repo root; in Git Bash prefix MSYS_NO_PATHCONV=1 so /kaggle paths survive):
    python kaggle/collusion-pilot/build.py -- --conditions nochat,chat_en --seeds 1,1 --rounds 20 --out /kaggle/working/run
then `kaggle kernels push -p kaggle/collusion-pilot`.
"""

import base64
import io
import json
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent

LAUNCHER = '''# Generated by kaggle/collusion-pilot/build.py; edit pilot/ and rebuild instead of editing this file.
import base64, io, os, subprocess, sys, tarfile
os.environ["HF_HOME"] = "/tmp/hf"  # /kaggle/working is capped at 20 GB; the model is ~19 GB
os.environ["PYTORCH_CUDA_ALLOC_CONF"] = "expandable_segments:True"
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "-U", "transformers", "accelerate"], check=True)
CODE = "/kaggle/working/code"
tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz").extractall(CODE, filter="data")
ARGS = {args!r}
proc = subprocess.Popen([sys.executable, "-u", "-m", "pilot.run", "--backend", "hf", *ARGS], cwd=CODE,
                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
for line in proc.stdout:
    print(line, end="", flush=True)
sys.exit(proc.wait())
'''


def bundle() -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for top in ("pilot", "third_party/sauer"):
            for path in sorted((ROOT / top).rglob("*")):
                if path.is_file() and "__pycache__" not in path.parts:
                    tar.add(path, arcname=str(path.relative_to(ROOT)))
    return base64.b64encode(buf.getvalue()).decode()


def main():
    args = sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else []
    script = f"BUNDLE = {bundle()!r}\n" + LAUNCHER.format(args=args)
    (HERE / "collusion_pilot.py").write_text(script, encoding="utf-8")
    meta = {
        "id": "pranavkasetty/collusion-pilot", "title": "collusion-pilot", "code_file": "collusion_pilot.py",
        "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
        "enable_tpu": False, "enable_internet": True, "dataset_sources": [], "kernel_sources": [],
        "competition_sources": [], "model_sources": [], "machine_shape": "NvidiaTeslaT4",
    }
    (HERE / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(f"wrote {HERE / 'collusion_pilot.py'} ({len(script) // 1024} KiB), args {args}")


if __name__ == "__main__":
    main()
